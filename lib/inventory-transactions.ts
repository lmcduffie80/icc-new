/**
 * Gets transaction history for a specific product
 */
export async function getProductTransactionHistory(
  productId: string,
  limit: number = 50
): Promise<InventoryTransaction[]> {
  return query<InventoryTransaction>(
    `SELECT * FROM inventory_transactions
     WHERE product_id = $1
     ORDER BY posting_date DESC, created_at DESC
     LIMIT $2`,
    [productId, limit]
  );
}

/**
 * Gets transaction history for a specific warehouse
 */
export async function getWarehouseTransactionHistory(
  warehouseId: string,
  limit: number = 50
): Promise<InventoryTransaction[]> {
  return query<InventoryTransaction>(
    `SELECT * FROM inventory_transactions
     WHERE warehouse_id = $1 
        OR from_warehouse_id = $1 
        OR to_warehouse_id = $1
     ORDER BY posting_date DESC, created_at DESC
     LIMIT $2`,
    [warehouseId, limit]
  );
}

/**
 * Gets recent transactions (for dashboard/overview)
 */
export async function getRecentTransactions(limit: number = 20): Promise<InventoryTransaction[]> {
  return query<InventoryTransaction>(
    `SELECT * FROM inventory_transactions
     ORDER BY created_at DESC
     LIMIT $1`,
    [limit]
  );
}
