/**
 * Logs an inventory adjustment (stock correction)
 */
export async function logInventoryAdjustment(params: {
  product_id: string;
  product_sku: string;
  product_name: string;
  quantity: number; // Positive for increase, negative for decrease
  unit_of_measure: string;
  warehouse_id: string;
  warehouse_name: string;
  storage_location?: string;
  unit_cost?: number;
  created_by_id?: string;
  created_by_username?: string;
  notes?: string;
  reason: string;
}): Promise<InventoryTransaction> {
  const isPositive = params.quantity > 0;

  return logInventoryTransaction({
    transaction_type: isPositive ? 'adjustment_positive' : 'adjustment_negative',
    product_id: params.product_id,
    product_sku: params.product_sku,
    product_name: params.product_name,
    quantity: params.quantity,
    unit_of_measure: params.unit_of_measure,
    warehouse_id: params.warehouse_id,
    warehouse_name: params.warehouse_name,
    storage_location: params.storage_location,
    reference_doc_type: 'adjustment',
    unit_cost: params.unit_cost,
    created_by_id: params.created_by_id,
    created_by_username: params.created_by_username,
    notes: `${params.reason}${params.notes ? ` - ${params.notes}` : ''}`,
  });
}

